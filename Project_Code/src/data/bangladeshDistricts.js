// Helper lookup functions
export function getDistrictById(id) {
  return BANGLADESH_DISTRICTS.find((d) => d.id === id);
}

export function getDistrictsByDivision(division) {
  if (!division || division === 'All') return BANGLADESH_DISTRICTS;
  return BANGLADESH_DISTRICTS.filter((d) => d.division === division);
}

export function searchDistrictsAndPlaces(query = '') {
  const q = query.trim().toLowerCase();
  if (!q) return BANGLADESH_DISTRICTS;

  return BANGLADESH_DISTRICTS.filter((district) => {
    const matchDistrict =
      district.name.toLowerCase().includes(q) ||
      district.bnName.includes(q) ||
      district.division.toLowerCase().includes(q);

    const matchPlace = district.places.some(
      (p) =>
        p.name.toLowerCase().includes(q) ||
        p.bnName.includes(q) ||
        p.category.toLowerCase().includes(q) ||
        p.description.toLowerCase().includes(q) ||
        p.highlights.toLowerCase().includes(q)
    );

    return matchDistrict || matchPlace;
  });
}
